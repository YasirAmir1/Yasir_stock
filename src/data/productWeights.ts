export function getProductWeight(productName: string): number | null {
  if (!productName) return null;
  const trimmed = productName.trim();
  if (PRODUCT_WEIGHTS_MAP[trimmed]) {
    return PRODUCT_WEIGHTS_MAP[trimmed];
  }
  const lower = trimmed.toLowerCase();
  for (const [key, weight] of Object.entries(PRODUCT_WEIGHTS_MAP)) {
    if (key.toLowerCase() === lower) {
      return weight;
    }
  }
  return null;
}
